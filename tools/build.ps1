# Builds everything on Windows as a normal user (no administrator rights):
# the UEFI menu, the settings app and the generated assets.
# Then run: .\install.cmd
#
#   tools\build.ps1
#
# Toolchains: the usual MSVC one works as it is. Without Visual Studio:
#   rustup toolchain install stable-x86_64-pc-windows-gnullvm
# next to rustup's stable-x86_64-pc-windows-gnu. The gnullvm toolchain brings
# its own linker (lld) and builds the app; this script passes the flags it
# needs. The gnu toolchain cannot build the app (its dlltool needs an
# assembler that rustup does not ship) but builds the UEFI menu.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

# The release whose generated assets are reused (see below).
$assetsTag = 'v0.2.0-beta'

$rustc = (rustc -vV | Out-String)
if ($LASTEXITCODE -ne 0) { throw 'rustc not found: install Rust from https://rustup.rs' }
$hostTriple = ([regex]::Match($rustc, 'host: (\S+)')).Groups[1].Value
if (-not (rustup target list --installed | Select-String 'x86_64-unknown-uefi')) {
    rustup target add x86_64-unknown-uefi
}
cargo build --release --target x86_64-unknown-uefi --manifest-path uefi/Cargo.toml
if ($LASTEXITCODE -ne 0) { throw 'building the UEFI menu failed' }

# The settings app.
$appToolchain = @()
if ($hostTriple -eq 'x86_64-pc-windows-gnu') {
    $gnullvm = 'stable-x86_64-pc-windows-gnullvm'
    if (-not (rustup toolchain list | Select-String $gnullvm)) {
        throw "the windows-gnu toolchain cannot build the settings app; run: rustup toolchain install $gnullvm"
    }
    $appToolchain = @("+$gnullvm")
    $hostTriple = 'x86_64-pc-windows-gnullvm'
}
if ($hostTriple -like '*-gnullvm' -and -not (Get-Command x86_64-w64-mingw32-clang -ErrorAction SilentlyContinue)) {
    # No clang driver installed: link with the bundled lld. It has no import
    # library for opengl32, but can link against a copy of the DLL itself.
    $libs = Join-Path $root 'target\winlibs'
    New-Item -ItemType Directory -Force $libs | Out-Null
    Copy-Item "$env:WINDIR\System32\opengl32.dll" $libs -Force
    $env:RUSTFLAGS = "-Clinker-flavor=ld.lld -Clinker=rust-lld -Clink-self-contained=yes -Lnative=$($libs.Replace('\', '/'))"
}
cargo @appToolchain build --release -p bootpick-config
if ($LASTEXITCODE -ne 0) { throw 'building the settings app failed' }

# Icons, flags, wallpapers and font subsets are generated by
# tools/build-assets.py, which needs cairo and the Noto fonts (Linux). They
# do not depend on the platform, so on Windows they come from a release.
$assets = Join-Path $root 'esp\EFI\bootpick'
$missing = @('icons', 'flags', 'fonts') | Where-Object { -not (Test-Path (Join-Path $assets $_)) }
if ($missing) {
    $url = "https://github.com/Devace-93/bootpick/releases/download/$assetsTag/bootpick-$assetsTag-x86_64-linux.tar.gz"
    $tmp = Join-Path $env:TEMP "bootpick-assets-$PID"
    New-Item -ItemType Directory -Force $tmp | Out-Null
    try {
        Write-Host "generated assets missing: downloading them from the $assetsTag release"
        Invoke-WebRequest -Uri $url -OutFile "$tmp\release.tar.gz" -UseBasicParsing
        & "$env:WINDIR\System32\tar.exe" -xzf "$tmp\release.tar.gz" -C $tmp
        if ($LASTEXITCODE -ne 0) { throw 'extracting the release failed' }
        $src = Get-ChildItem $tmp -Directory | Select-Object -First 1
        New-Item -ItemType Directory -Force $assets | Out-Null
        foreach ($d in 'icons', 'flags', 'fonts', 'backgrounds') {
            Copy-Item (Join-Path $src.FullName "esp\EFI\bootpick\$d") $assets -Recurse -Force
        }
    } finally {
        Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue
    }
}
Write-Host 'built. Now: .\install.cmd'
