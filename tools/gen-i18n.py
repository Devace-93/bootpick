#!/usr/bin/env python3
"""Generates core/src/i18n_data.rs from assets/i18n/{strings,langs}.json and
config/src/i18n_app.rs from assets/i18n/app.json (the settings app).

Run after editing the catalog:  python3 tools/gen-i18n.py
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
strings = json.load(open(os.path.join(ROOT, "assets/i18n/strings.json")))
langs = json.load(open(os.path.join(ROOT, "assets/i18n/langs.json")))
keys = strings.pop("_keys")


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = ["// @generated by tools/gen-i18n.py from assets/i18n/*.json. Do not edit.", ""]
out.append("/// Message keys, in table column order.")
out.append("#[derive(Clone, Copy, PartialEq, Eq, Debug)]")
out.append("#[allow(non_camel_case_types, dead_code)]")
out.append("pub enum Msg {")
for k in keys:
    out.append(f"    {k},")
out.append("}")
out.append("")
out.append(f"pub const KEY_COUNT: usize = {len(keys)};")
out.append("")
out.append("/// (base language, strings in `Msg` order)")
out.append(f"pub static TABLE: &[(&str, [&str; KEY_COUNT])] = &[")
for base, vals in strings.items():
    out.append(f"    ({lit(base)}, [")
    for v in vals:
        out.append(f"        {lit(v)},")
    out.append("    ]),")
out.append("];")
out.append("")
out.append("/// (code, country for the flag, native name)")
out.append("pub static LANGS: &[(&str, &str, &str)] = &[")
for l in langs:
    out.append(f"    ({lit(l['code'])}, {lit(l['country'])}, {lit(l['name'])}),")
out.append("];")
open(os.path.join(ROOT, "core/src/i18n_data.rs"), "w").write("\n".join(out) + "\n")
print(f"{len(keys)} keys x {len(strings)} languages, {len(langs)} locales")

app_path = os.path.join(ROOT, "assets/i18n/app.json")
if os.path.exists(app_path):
    app = json.load(open(app_path))
    akeys = app.pop("_keys")
    o = ["// @generated by tools/gen-i18n.py from assets/i18n/app.json. Do not edit.", ""]
    o.append("#[derive(Clone, Copy, PartialEq, Eq, Debug)]")
    o.append("#[allow(non_camel_case_types, dead_code)]")
    o.append("pub enum T {")
    o += [f"    {k}," for k in akeys]
    o.append("}")
    o.append("")
    o.append(f"pub const COUNT: usize = {len(akeys)};")
    o.append("")
    o.append("pub static TABLE: &[(&str, [&str; COUNT])] = &[")
    for base, vals in app.items():
        assert len(vals) == len(akeys), base
        o.append(f"    ({lit(base)}, [")
        o += [f"        {lit(v)}," for v in vals]
        o.append("    ]),")
    o.append("];")
    open(os.path.join(ROOT, "config/src/i18n_app.rs"), "w").write("\n".join(o) + "\n")
    print(f"app: {len(akeys)} keys x {len(app)} languages")
